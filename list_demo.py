# Day 3 上：列表（list）—— 一个"装多个数据"的有序盒子
# 列表用方括号 [] 表示，里面的数据用逗号隔开

# 1. 定义一个装素林体重记录的列表（斤）
weights = [160, 158, 155, 150]   # 第1~4周的体重
print("我的体重记录：", weights)

# 2. 取列表里的某一个数据 —— 用"下标"，从 0 开始数！
#   第1周是下标0，第2周是下标1……以此类推
first = weights[0]
print("第一周体重：", first)
last = weights[-1]      # 小技巧：-1 表示"倒数第一个"
print("最近一周体重：", last)

# 3. 数一数列表里有几个数据：用 len()
print("一共记录了", len(weights), "周")

# 4. 往列表里加一个新数据：append() = 追加到末尾
weights.append(152)
print("加了新一周后：", weights)

# 5. 改掉列表里某个数据（按下标改）
weights[1] = 160      # 把第2周（下标1）的 162 改成 160
print("改完之后：", weights)

# 6. 列表里不仅能装数字，也能混装文字、甚至其他列表
mixed = ["素林", 30, 165.5, ["跑步", "游泳"]]
print("混合列表：", mixed)
print("混合列表里的第4项（又是个列表）：", mixed[3])
